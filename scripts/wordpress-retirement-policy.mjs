import fs from 'node:fs/promises';

export const origin = 'https://tuxar.co.uk';
export const begin = '# BEGIN TUXAR WORDPRESS RETIREMENT';
export const end = '# END TUXAR WORDPRESS RETIREMENT';
export const queryIdentity = '(^|&)(product|page_id|p|paged|post_type|add-to-cart)(=|%3d|&|$)|(^|&)(ND|SA|MD)(=|&|$)';
export const legacyQueryPath = '^(?:index\\.php|(?:shop|checkout|cart|wishlist)/?)?$';
export const legacyNamespace = '^(?:product|product-category|product-tag|tag|category)(?:/|$)';
const escape = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export async function loadPolicy() {
  const source = JSON.parse(await fs.readFile('output/wordpress-retirement-20261028/source-urls.json', 'utf8'));
  const sitemap = await fs.readFile('public/sitemap.xml', 'utf8');
  const english = new Set([...sitemap.matchAll(/<loc>(https:\/\/tuxar\.co\.uk\/en(?:\/[^<]*)?)<\/loc>/g)].map(match => match[1]));
  const maps = new Map([
    ['/shop', `${origin}/en/shop`],
    ['/wishlist', `${origin}/en/wishlist`],
    ['/product-category/motorcycle-gloves', `${origin}/en/accessories`],
    ['/product-category/motorcycle-jacket/leather-jacket/bomber-jacket', `${origin}/en/collections/bomber-jackets`],
    ['/product-category/motorcycle-jacket/leather-jacket/textile-jacket', `${origin}/en/collections/textile-jackets`],
    ['/product-category/motorcycle-jacket/leather-jacket/puffer-jacket', `${origin}/en/collections/leather-puffer-jackets`],
  ]);
  for (const url of english) {
    const pathname = new URL(url).pathname;
    if (pathname.startsWith('/en/product/')) maps.set(pathname.slice(3), url);
    if (pathname.startsWith('/en/blog/')) maps.set(pathname.slice('/en/blog'.length), url);
  }
  for (const [old, destination] of maps) {
    if (old !== '/wishlist' && !english.has(destination)) throw new Error(`Destination is not a published English URL: ${destination}`);
  }
  const articles = new Set(source.urls.filter(row => !new URL(row.url).search).map(row => new URL(row.url).pathname.replace(/\/$/, '')).filter(pathname => /^\/[a-z0-9-]+$/.test(pathname) && !maps.has(pathname) && !['/en', '/it', '/de', '/fr', '/es', '/checkout', '/cart', '/wp-admin'].includes(pathname)));
  function decide(input) {
    const url = new URL(input, origin);
    const pathname = decodeURIComponent(url.pathname).replace(/\/$/, '') || '/';
    if (/^\/wp-admin(?:\/|$)/i.test(pathname)) return { status: 403, reason: 'WordPress administration remains forbidden; never redirected.' };
    const oldQuery = new RegExp(queryIdentity, 'i').test(url.search.slice(1));
    const product = [...url.searchParams].find(([key]) => key.toLowerCase() === 'product')?.[1];
    if (['/', '/index.php'].includes(pathname) && product && maps.has(`/product/${product.toLowerCase()}`)) return { status: 301, destination: maps.get(`/product/${product.toLowerCase()}`), reason: 'Exact current product slug; discard obsolete WordPress identity/action query.' };
    if (new RegExp(legacyQueryPath, 'i').test(pathname.slice(1)) && oldQuery) return { status: 410, reason: 'Obsolete WordPress query identity/action on an old entry point; no verified replacement.' };
    const match = [...maps].find(([old]) => old.toLowerCase() === pathname.toLowerCase());
    if (match) return { status: 301, destination: match[1] + (oldQuery ? '' : url.search), reason: pathname.startsWith('/product-category/') ? 'Same category intent and a populated matching current category; no product-level identity guessed.' : 'Exact current product/article slug or same shop/wishlist function.' };
    if (new RegExp(legacyNamespace, 'i').test(pathname.slice(1)) || articles.has(pathname.toLowerCase())) return { status: 410, reason: 'Retired WordPress resource; no proven equivalent in the current catalogue or articles.' };
    return { status: 200, reason: 'Current route or ordinary query; leave existing routing unchanged.' };
  }
  const lines = [begin,
    '  # Generated by scripts/prepare-wordpress-retirement.mjs; do not edit mappings here.',
    '  ErrorDocument 404 /legacy-not-found.html',
    '  ErrorDocument 410 /legacy-not-found.html',
    '  RewriteCond %{ENV:REDIRECT_STATUS} ^(404|410)$',
    '  RewriteRule ^legacy-not-found\\.html$ - [L]',
    '  # A product query is redirected only when its exact slug exists today.',
  ];
  for (const [old, destination] of maps) if (old.startsWith('/product/')) {
    lines.push(`  RewriteCond %{QUERY_STRING} (^|&)product=${escape(old.slice('/product/'.length))}(&|$) [NC]`, `  RewriteRule ^(?:index\\.php)?$ ${destination} [R=301,L,NE,QSD]`);
  }
  lines.push('  # Bounded WordPress keys at legacy entry points only. Modern /en/... routes are excluded.', `  RewriteCond %{QUERY_STRING} ${queryIdentity} [NC]`, `  RewriteRule ${legacyQueryPath} - [G,L,NC,QSD]`, '  # Same-resource replacements. Ordinary tracking/search parameters are retained.');
  for (const [old, destination] of maps) {
    const pattern = `^${escape(old.slice(1))}/?$`;
    lines.push(`  RewriteCond %{QUERY_STRING} ${queryIdentity} [NC]`, `  RewriteRule ${pattern} ${destination} [R=301,L,NC,NE,QSD]`, `  RewriteRule ${pattern} ${destination} [R=301,L,NC,NE]`);
  }
  lines.push('  # All remaining resources in these retired WordPress namespaces are permanently gone.', `  RewriteRule ${legacyNamespace} - [G,L,NC,QSD]`, '  # Exact old article paths from Search Console, never a blanket top-level path rule.');
  for (const article of [...articles].sort()) lines.push(`  RewriteRule ^${escape(article.slice(1))}/?$ - [G,L,NC,QSD]`);
  lines.push(end);
  return { source, maps, articles, decide, block: lines.join('\n') };
}
